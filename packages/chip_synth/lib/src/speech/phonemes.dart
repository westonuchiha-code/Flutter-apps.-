// English speech sounds (ARPAbet names) as formant targets.
// Values are textbook adult-male averages (Peterson & Barney style).

enum PhonemeKind {
  vowel,
  diphthong,
  approximant,
  nasal,
  fricative,
  stop,
  affricate,
  pause,
}

/// One speech sound: where the vocal tract resonances sit, how much voice
/// and hiss it has, and how long it lasts at normal speed.
class Phoneme {
  const Phoneme(
    this.code,
    this.example,
    this.kind,
    this.f1,
    this.f2,
    this.f3, {
    this.voice = 1,
    this.noise = 0,
    this.noiseHz = 0,
    this.ms = 100,
    this.glideTo,
    this.burstHz = 0,
    this.voicedStop = false,
  });

  /// ARPAbet name, e.g. `AA`.
  final String code;

  /// A word containing the sound (for the help list).
  final String example;
  final PhonemeKind kind;
  final double f1, f2, f3;

  /// Voicing (buzz) and frication (hiss) amounts, 0..1.
  final double voice, noise;

  /// Centre of the hiss; 0 means the hiss goes through the formants
  /// (aspiration, like H).
  final double noiseHz;

  /// Typical length in milliseconds.
  final double ms;

  /// Diphthongs move towards this sound.
  final String? glideTo;

  /// Stops: the burst's centre frequency.
  final double burstHz;
  final bool voicedStop;

  bool get isVowel =>
      kind == PhonemeKind.vowel || kind == PhonemeKind.diphthong;
}

