// Generates lib/src/tables.dart: the MP3 Huffman codes and the subband
// filter's window, read from the MP3 decoder flutter_soloud ships
// (dr_mp3.h), so what we write is exactly what our apps play back.
//   dart run tool/gen_tables.dart <path to dr_mp3.h>
import 'dart:io';
import 'dart:math' as math;

List<int> _array(String src, String name) {
  final m = RegExp('$name\\[[^\\]]*\\]\\s*=\\s*\\{([^}]*)\\}').firstMatch(src)!;
  return [
    for (final t in m.group(1)!.split(','))
      if (t.trim().isNotEmpty) int.parse(t.trim().replaceAll('f', '')),
  ];
}

void main(List<String> args) {
  final src = File(args.first).readAsStringSync();
  final tabs = _array(src, 'tabs');
  final tab32 = _array(src, 'tab32');
  final tab33 = _array(src, 'tab33');
  final tabindex = _array(src, 'tabindex');
  final out = StringBuffer()
    ..writeln(
      '// GENERATED by tool/gen_tables.dart from dr_mp3.h. Do not edit.',
    )
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln();

  // Big-value tables: decode every 19-bit string, keep the code of each pair.
  out.writeln('/// Huffman codes per table (1..31; 0, 4, 14 unused): for pair');
  out.writeln('/// x*16+y, code << 5 | length.');
  out.writeln('const huffCodes = <int, List<int>>{');
  for (var t = 1; t < 32; t++) {
    if (t == 4 || t == 14 || (t > 16 && t < 24) || t > 24) continue;
    final base = tabindex[t];
    final codes = List.filled(256, 0);
    const bits = 19;
    for (var b = 0; b < (1 << bits); b++) {
      var cache = b << (32 - bits);
      var used = 0;
      var w = 5;
      var leaf = tabs[base + (cache >>> (32 - w))];
      while (leaf < 0) {
        cache = (cache << w) & 0xFFFFFFFF;
        used += w;
        w = leaf & 7;
        leaf = tabs[base + (cache >>> (32 - w)) - (leaf >> 3)];
      }
      final len = used + (leaf >> 8);
      final x = leaf & 15, y = (leaf >> 4) & 15;
      final code = b >> (bits - len);
      final prev = codes[x * 16 + y];
      if (prev == 0) {
        codes[x * 16 + y] = code << 5 | len;
      } else if (prev != (code << 5 | len)) {
        throw StateError('table $t pair $x,$y two codes');
      }
    }
    out.writeln('  $t: [${codes.join(',')}],');
  }
  out.writeln('};');

  // Count1 tables A (tab32) and B (tab33): index v*8+w*4+x*2+y.
  for (final (name, table, isB) in [
    ('count1A', tab32, false),
    ('count1B', tab33, true),
  ]) {
    final codes = List.filled(16, 0);
    for (var b = 0; b < 64; b++) {
      final cache = b << 26;
      var leaf = table[cache >>> 28];
      if (!isB && (leaf & 8) == 0) {
        leaf =
            table[(leaf >> 3) +
                (((cache << 4) & 0xFFFFFFFF) >>> (32 - (leaf & 3)))];
      }
      final len = leaf & 7;
      final v = (leaf >> 7) & 1,
          w = (leaf >> 6) & 1,
          x = (leaf >> 5) & 1,
          y = (leaf >> 4) & 1;
      codes[v * 8 + w * 4 + x * 2 + y] = (b >> (6 - len)) << 5 | len;
    }
    out.writeln('const $name = [${codes.join(',')}];');
  }
  File('lib/src/tables.dart').writeAsStringSync(out.toString());
  stdout.writeln('ok ${math.pi}');
}
